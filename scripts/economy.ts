const fullCreditWins = fullUpgradeCost('common') / 100;
L.push(`At Bronze/Normal victory rates, level 30 needs ${fullXpWins.toFixed(0)} wins of XP, while maximising the six attributes needs ${fullCreditWins.toFixed(0)} wins of Credits (before defeat/draw income and starting Credits). **Credits are the primary bottleneck** (about ${(fullCreditWins / fullXpWins).toFixed(1)}x XP). Level gates only briefly delay purchases: rank 10 needs level 25 (${cumulativeXpForLevel(25).toLocaleString()} XP, ${(cumulativeXpForLevel(25) / 50).toFixed(0)} wins), long before the Credits for the last ranks are earned.`, '');
