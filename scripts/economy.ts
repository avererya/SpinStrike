// ---- Part B: projection
L.push('## Part B: projected full-career economy (NOT implemented)', '');
L.push('Assumptions: flat win rate; draw rate 5 %; rank advancement needs 10/20/30 wins in Bronze III/II/I (provisional, implemented) and an ASSUMED 30 wins per division above Bronze; the player fights opponents of their own rank tier and rewards use the approved per-tier table at Normal difficulty unless stated.', '');
const tierOfIndex = (i: number): RankTier => RANK_LADDER[Math.min(i, RANK_LADDER.length - 1)]!.tier;
function project(winRate: number, diff: Difficulty, winsPerRank: (i: number) => number): { battlesAllMaxed: number; battlesL30: number; battlesAttr: number; avgCredit: number } {
  let credits = 500, xp = 0, level = 1, rankIdx = 0, rankWins = 0;
  const ranks: Record<string, number> = Object.fromEntries(UPGRADE_STATS.map((s) => [s, 0]));
  let battles = 0, L30 = 0, attr = 0;
  while (battles < 20000) {
    battles++;
    const tier = tierOfIndex(rankIdx);
    const r = calculateReward(tier, diff, 'win'), l = calculateReward(tier, diff, 'loss'), d = calculateReward(tier, diff, 'draw');
    const pd = 0.05, pl = 1 - winRate - pd;
    credits += winRate * r.credits + pl * l.credits + pd * d.credits;
    xp += winRate * r.xp + pl * l.xp + pd * d.xp;
    while (level < 30 && xp >= 100 + 25 * (level - 1)) { xp -= 100 + 25 * (level - 1); level++; }
    if (level >= 30 && !L30) L30 = battles;
    rankWins += winRate;
    if (rankWins >= winsPerRank(rankIdx) && rankIdx < RANK_LADDER.length - 1) { rankIdx++; rankWins = 0; }
    for (let guard = 0; guard < 100; guard++) {
      const order = UPGRADE_STATS.slice().sort((a, b) => ranks[a]! - ranks[b]!);
      let bought = false;
      for (const s of order) {
        const nx = ranks[s]! + 1;
        if (nx <= MAX_UPGRADE_RANK && nx <= maxRankForLevel(level) && credits >= upgradeCost('common', nx)) { credits -= upgradeCost('common', nx); ranks[s] = nx; bought = true; break; }
      }
      if (!bought) break;
    }
    if (!attr && UPGRADE_STATS.some((s) => ranks[s] === MAX_UPGRADE_RANK)) attr = battles;
    if (UPGRADE_STATS.every((s) => ranks[s] === MAX_UPGRADE_RANK)) return { battlesAllMaxed: battles, battlesL30: L30, battlesAttr: attr, avgCredit: 0 };
  }
  return { battlesAllMaxed: -1, battlesL30: L30, battlesAttr: attr, avgCredit: 0 };
}
const projAvg = 33; // seconds, typical measured average
const per = (b: number) => (b < 0 ? 'n/a' : `${((b * (projAvg + OVERHEAD_S)) / 3600).toFixed(1)} h (${b})`);
const wpr = (i: number) => (i < 3 ? [10, 20, 30][i]! : 30);
L.push('### By win rate (Normal difficulty)', '', '| Win rate | Level 30 | 1st attribute maxed | All 6 attributes maxed |', '|---|---|---|---|');
for (const w of [0.5, 0.65, 0.8, 0.95]) { const p = project(w, 'normal', wpr); L.push(`| ${(w * 100).toFixed(0)} % | ${per(p.battlesL30)} | ${per(p.battlesAttr)} | ${per(p.battlesAllMaxed)} |`); }
L.push('', '### By difficulty (win rate 80 %, rewards as approved)', '', '| Difficulty | Reward mult | All 6 maxed |', '|---|---|---|');
for (const d of DIFFICULTIES) { const p = project(0.8, d, wpr); L.push(`| ${DIFFICULTY_LABEL[d]} | ${DIFFICULTY_REWARD_PERCENT[d] / 100}x | ${per(p.battlesAllMaxed)} |`); }
L.push('', '### Bronze-only vs full ladder (Normal, 80 % win rate)', '');
const bronzeOnly = project(0.8, 'normal', () => 1e9);
const fullLadder = project(0.8, 'normal', wpr);
L.push(`- Bronze rewards forever: ${per(bronzeOnly.battlesAllMaxed)}`, `- Climbing the assumed ladder: ${per(fullLadder.battlesAllMaxed)}`, '');
L.push('### Expert reward check', '');
const exH = project(0.8, 'expert', wpr), noH = project(0.8, 'normal', wpr);
L.push(`Expert pays 2x Credits and XP but, today, only improves the opponent's *launch* quality (Perfect 50 %, never Poor). Measured Inferno career win rates are in Part A. Expert reaches a fully upgraded top in ${per(exH.battlesAllMaxed)} versus ${per(noH.battlesAllMaxed)} on Normal. If Expert win rate is close to Normal's, the 2x multiplier is a free doubling of income; see the report recommendation.`, '');

