  L.push(`| ${label} | ${hrs(b.firstUpgrade!, m.avgDuration)} | ${hrs(b.tenUpgrades!, m.avgDuration)} | ${hrs(b.level5!, m.avgDuration)} | ${hrs(b.level10!, m.avgDuration)} | ${hrs(b.level20!, m.avgDuration)} | ${hrs(b.level30!, m.avgDuration)} | ${hrs(b.firstAttributeMaxed!, m.avgDuration)} | ${hrs(b.allMaxed!, m.avgDuration)} | ${(m.winRate * 100).toFixed(0)} % | ${m.avgDuration.toFixed(0)} s |`);
